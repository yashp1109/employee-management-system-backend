create table departments (
    id bigint generated by default as identity primary key,
    name varchar(120) not null unique,
    description varchar(500)
);

create table designations (
    id bigint generated by default as identity primary key,
    name varchar(120) not null unique,
    description varchar(500),
    department_id bigint references departments (id)
);

create table employees (
    id bigint generated by default as identity primary key,
    employee_code varchar(30) not null unique,
    first_name varchar(80) not null,
    last_name varchar(80) not null,
    email varchar(160) not null unique,
    mobile_number varchar(20),
    gender varchar(20) not null,
    date_of_birth date,
    date_of_joining date,
    department_id bigint references departments (id),
    designation_id bigint references designations (id),
    salary numeric(12, 2) not null check (salary >= 0),
    manager_id bigint references employees (id),
    status varchar(20) not null,
    role varchar(20) not null,
    password_hash varchar(255) not null,
    created_at timestamptz,
    updated_at timestamptz
);

create index idx_employee_email on employees (email);

create index idx_employee_code on employees (employee_code);

create table leave_types (
    id bigint generated by default as identity primary key,
    name varchar(80) not null unique,
    annual_quota integer not null check (annual_quota >= 0)
);

create table leave_balances (
    id bigint generated by default as identity primary key,
    employee_id bigint not null references employees (id) on delete cascade,
    leave_type_id bigint not null references leave_types (id),
    year integer not null,
    total_days integer not null check (total_days >= 0),
    used_days integer not null default 0 check (used_days >= 0),
    constraint uk_leave_balance_employee_type_year unique (
        employee_id,
        leave_type_id,
        year
    )
);

create table leave_requests (
    id bigint generated by default as identity primary key,
    employee_id bigint not null references employees (id) on delete cascade,
    leave_type_id bigint not null references leave_types (id),
    start_date date not null,
    end_date date not null,
    days integer not null check (days > 0),
    reason varchar(500) not null,
    status varchar(20) not null,
    approved_by bigint references employees (id),
    approved_at timestamptz,
    created_at timestamptz,
    updated_at timestamptz,
    constraint chk_leave_dates check (end_date >= start_date)
);

create table attendances (
    id bigint generated by default as identity primary key,
    employee_id bigint not null references employees (id) on delete cascade,
    attendance_date date not null,
    check_in_time time,
    check_out_time time,
    working_hours numeric(5, 2),
    constraint uk_attendance_employee_date unique (employee_id, attendance_date)
);

