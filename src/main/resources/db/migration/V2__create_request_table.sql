create table requests (
    id bigint generated by default as identity primary key,
    type varchar(60) not null,
    employee_id bigint not null references employees (id) on delete cascade,
    requested_by bigint not null references employees (id),
    comment text,
    payload jsonb,
    status varchar(20) not null default 'PENDING',
    reviewer_id bigint references employees (id),
    reviewer_comment text,
    created_at timestamptz default now(),
    updated_at timestamptz default now()
);

create index idx_requests_employee_id on requests (employee_id);

create index idx_requests_requested_by on requests (requested_by);

create index idx_requests_status on requests (status);